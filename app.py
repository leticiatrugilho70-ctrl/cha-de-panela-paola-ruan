@app.before_request
def protect_admin():
    if request.path.startswith('/admin'):
        admin_password = os.environ.get('ADMIN_PASSWORD')
        auth = request.authorization

        if (
            not admin_password
            or not auth
            or auth.username != 'admin'
            or auth.password != admin_password
        ):
            return (
                'Acesso restrito',
                401,
                {'WWW-Authenticate': 'Basic realm="Painel administrativo"'}
            )


def conn():
    return psycopg2.connect(
        os.environ['DATABASE_URL'],
        cursor_factory=psycopg2.extras.RealDictCursor
    )


def export_choices(c=None):
    own = c is None

    if own:
        c = conn()

    with c.cursor() as cur:
        cur.execute(
            '''
            SELECT h.id, h.guest_name, h.gift_name, h.chosen_at, h.active
            FROM choice_history h
            ORDER BY h.id DESC
            '''
        )
        rows = cur.fetchall()

    wb = Workbook()
    ws = wb.active
    ws.title = 'Escolhas'

    ws.append([
        'Nome do convidado',
        'Presente escolhido',
        'Data e hora',
        'Status'
    ])

    for r in rows:
        ws.append([
            r['guest_name'],
            r['gift_name'],
            r['chosen_at'],
            'Ativa' if r['active'] else 'Liberada'
        ])

    ws.column_dimensions['A'].width = 28
    ws.column_dimensions['B'].width = 42
    ws.column_dimensions['C'].width = 22
    ws.column_dimensions['D'].width = 14

    wb.save(EXPORT)

    if own:
        c.close()


def init_db():
    c = conn()

    try:
        with c.cursor() as cur:
            cur.execute(
                '''
                CREATE TABLE IF NOT EXISTS gifts(
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name TEXT NOT NULL,
                    link TEXT,
                    image TEXT,
                    status TEXT NOT NULL DEFAULT 'disponivel',
                    chosen_by TEXT,
                    chosen_at TEXT
                )
                '''
            )

            cur.execute(
                '''
                CREATE TABLE IF NOT EXISTS settings(
                    key TEXT PRIMARY KEY,
                    value TEXT
                )
                '''
            )

            cur.execute(
                '''
                CREATE TABLE IF NOT EXISTS choice_history(
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    gift_id INTEGER,
                    guest_name TEXT NOT NULL,
                    gift_name TEXT NOT NULL,
                    chosen_at TEXT NOT NULL,
                    active INTEGER NOT NULL DEFAULT 1
                )
                '''
            )

            cur.execute('SELECT COUNT(*) AS n FROM gifts')
            count = cur.fetchone()['n']

            if count == 0:
                data = json.loads(
                    (BASE / 'items.json').read_text(encoding='utf-8')
                )

                for item in data:
                    cur.execute(
                        '''
                        INSERT INTO gifts(id, name, link, image)
                        VALUES(%s, %s, %s, %s)
                        ''',
                        (
                            item['id'],
                            item['name'],
                            item.get('link'),
                            item.get('image')
                        )
                    )

            defaults = {
                'title': 'Lista de Presentes',
                'subtitle': 'Chá de Panela',
                'couple': 'Paola & Ruan',
                'intro': 'Cada presente escolhido com amor levará um pedacinho de vocês para o nosso novo lar, fazendo parte dos sonhos e da linda história que estamos construindo juntos.',
                'primary': '#82a8c5',
                'secondary': '#d8edf9',
                'background': '#fbfaf5'
            }

            for k, v in defaults.items():
                cur.execute(
                    '''
                    INSERT INTO settings(key, value)
                    VALUES(%s, %s)
                    ON CONFLICT (key) DO NOTHING
                    ''',
                    (k, v)
                )

        c.commit()

    except Exception:
        c.rollback()
        raise

    finally:
        c.close()


