@app.post('/api/reserve/<int:gift_id>')
def reserve(gift_id):
    name = (request.json or {}).get('name', '').strip()

    if not name:
        return jsonify(
            ok=False,
            message='Digite seu nome.'
        ), 400

    c = conn()

    try:
        with c.cursor() as cur:
            cur.execute(
                '''
                SELECT name, status
                FROM gifts
                WHERE id=%s
                FOR UPDATE
                ''',
                (gift_id,)
            )

            row = cur.fetchone()

            if not row:
                c.rollback()
                return jsonify(
                    ok=False,
                    message='Presente não encontrado.'
                ), 404

            if row['status'] != 'disponivel':
                c.rollback()
                return jsonify(
                    ok=False,
                    message='Esse presente acabou de ser escolhido por outra pessoa. Escolha outro presente.'
                ), 409

            now = datetime.now().strftime('%d/%m/%Y %H:%M:%S')

            cur.execute(
                '''
                UPDATE gifts
                SET status='escolhido',
                    chosen_by=%s,
                    chosen_at=%s
                WHERE id=%s
                  AND status='disponivel'
                ''',
                (name, now, gift_id)
            )

            if cur.rowcount != 1:
                c.rollback()
                return jsonify(
                    ok=False,
                    message='Esse presente acabou de ser escolhido por outra pessoa. Escolha outro presente.'
                ), 409

            cur.execute(
                '''
                INSERT INTO choice_history(
                    gift_id,
                    guest_name,
                    gift_name,
                    chosen_at
                )
                VALUES(%s, %s, %s, %s)
                ''',
                (
                    gift_id,
                    name,
                    row['name'],
                    now
                )
            )

        c.commit()

        return jsonify(
            ok=True,
            message='Presente escolhido com carinho! Obrigada por fazer parte desse momento tão especial.'
        )

    except Exception:
        c.rollback()
        raise

    finally:
        c.close()



def save_upload(file):
    if not file or not file.filename:
        return None

    ext = Path(secure_filename(file.filename)).suffix.lower()

    if ext not in ALLOWED:
        raise ValueError('Formato de imagem não permitido.')

    name = f'gift-{uuid.uuid4().hex}{ext}'

    supabase = create_client(
        os.environ['SUPABASE_URL'],
        os.environ['SUPABASE_KEY']
    )

    file.stream.seek(0)
    supabase.storage.from_('presentes').upload(
        path=name,
        file=file.stream.read(),
        file_options={
            'content-type': file.mimetype or 'application/octet-stream',
            'upsert': 'false'
        }
    )

    return supabase.storage.from_('presentes').get_public_url(name)



@app.route('/admin', methods=['GET', 'POST'])
def admin():
    c = conn()

    try:
        with c.cursor() as cur:
            if request.method == 'POST':
                for k in [
                    'title',
                    'subtitle',
                    'couple',
                    'intro',
                    'primary',
                    'secondary',
                    'background'
                ]:
                    cur.execute(
                        '''
                        INSERT INTO settings(key, value)
                        VALUES(%s, %s)
                        ON CONFLICT (key)
                        DO UPDATE SET value=EXCLUDED.value
                        ''',
                        (
                            k,
                            request.form.get(k, '')
                        )
                    )

                c.commit()
                return redirect(url_for('admin'))

            cur.execute(
                'SELECT * FROM gifts ORDER BY id'
            )
            gifts = [
                dict(r)
                for r in cur.fetchall()
            ]

            cur.execute(
                'SELECT key, value FROM settings'
            )
            settings = {
                r['key']: r['value']
                for r in cur.fetchall()
            }

            cur.execute(
                '''
                SELECT *
                FROM choice_history
                ORDER BY id DESC
                LIMIT 100
                '''
            )
            history = [
                dict(r)
                for r in cur.fetchall()
            ]

    finally:
        c.close()

    return render_template(
        'admin.html',
        gifts=gifts,
        settings=settings,
        history=history
    )


@app.post('/admin/gift/add')
def add_gift():
    name = request.form.get(
        'name',
        ''
    ).strip()

    link = request.form.get(
        'link',
        ''
    ).strip()

    if not name:
        return redirect(url_for('admin'))

    try:
        image = save_upload(
            request.files.get('image')
        )
    except ValueError:
        image = None

    c = conn()

    try:
        with c.cursor() as cur:
            cur.execute(
                '''
                INSERT INTO gifts(name, link, image)
                VALUES(%s, %s, %s)
                ''',
                (name, link, image)
            )

        c.commit()

    except Exception:
        c.rollback()
        raise

    finally:
        c.close()

    return redirect(url_for('admin'))


@app.post('/admin/gift/<int:gift_id>/edit')
def edit_gift(gift_id):
    c = conn()

    try:
        with c.cursor() as cur:
            cur.execute(
                '''
                SELECT image
                FROM gifts
                WHERE id=%s
                ''',
                (gift_id,)
            )

            row = cur.fetchone()

            if not row:
                return redirect(url_for('admin'))

            image = row['image']

            try:
                new = save_upload(
                    request.files.get('image')
                )
                image = new or image
            except ValueError:
                pass

            cur.execute(
                '''
                UPDATE gifts
                SET name=%s,
                    link=%s,
                    image=%s
                WHERE id=%s
                ''',
                (
                    request.form.get(
                        'name',
                        ''
                    ).strip(),
                    request.form.get(
                        'link',
                        ''
                    ).strip(),
                    image,
                    gift_id
                )
            )

        c.commit()

    except Exception:
        c.rollback()
        raise

    finally:
        c.close()

    return redirect(url_for('admin'))


