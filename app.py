@app.post('/admin/reset/<int:gift_id>')
def reset(gift_id):
    c = conn()

    try:
        with c.cursor() as cur:
            cur.execute(
                '''
                UPDATE gifts
                SET status='disponivel',
                    chosen_by=NULL,
                    chosen_at=NULL
                WHERE id=%s
                ''',
                (gift_id,)
            )

            cur.execute(
                '''
                UPDATE choice_history
                SET active=0
                WHERE gift_id=%s
                  AND active=1
                ''',
                (gift_id,)
            )

        c.commit()

    except Exception:
        c.rollback()
        raise

    finally:
        c.close()

    return redirect(url_for('admin'))


